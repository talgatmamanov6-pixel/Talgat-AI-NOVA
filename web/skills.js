function build(id, options={}){
 const skill=items.find(s=>s.id===id);if(!skill)throw new Error('Неизвестная команда');
 const topic=String(options.topic||'').trim().slice(0,6000);if(!topic)throw new Error('Укажите тему, задачу или исходный текст');
 return 'Сценарий: /'+id+' — '+skill.title+'\n\nЗадача и исходные данные:\n'+topic+'\n\nАудитория / уровень: '+String(options.audience||'не указан').slice(0,160)+'\nОбъём / длительность: '+String(options.scope||'подбери разумный').slice(0,160)+'\nЯзык результата: '+String(options.language||'русский').slice(0,40)+'\n\nТребования к результату:\n'+skill.instruction+'\nЕсли критически не хватает данных, задай до 3 конкретных вопросов. В остальных случаях явно укажи допущения и выполни задачу. Не добавляй декоративные символы.';
}
function expand(text){const match=text.trim().match(/^\/([a-z-]+)(?:\s+([\s\S]*))?$/);if(!match)return null;const skill=items.find(s=>s.id===match[1]);if(!skill)return null;return {skill,prompt:match[2]?build(skill.id,{topic:match[2]}):null}}
function csv(table){return [...table.rows].map(row=>[...row.cells].map(cell=>{let value=cell.textContent.replace(/\r?\n/g,' ').trim();if(/^[=+\-@\t\r]/.test(value))value="'"+value;return '"'+value.replace(/"/g,'""')+'"'}).join(',')).join('\r\n')}
